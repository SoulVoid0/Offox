#!/usr/bin/env python3
# Turns a Firefox ESR source tree into Offox.
#
# This repository already *is* the Firefox ESR source with Offox applied.
# Use this script to move Offox to a newer Firefox release:
#
#   python3 offox/fork/apply.py <new firefox source folder> [--mozconfig linux|windows]
#
# Running it on this repository itself (python3 offox/fork/apply.py .) only
# regenerates browser/components/offox/jar.mn after files were added there.
#
# What it does (safe to run again on an already patched tree):
#   1. applies fork/patches/*.patch (portable mode, about:offox, startup hook,
#      offline prefs include, Offox Sites menu items and the Settings and
#      address bar changes)
#   2. copies src/offox to browser/components/offox and writes its moz.build
#      and jar.mn (resource://offox/ and chrome://offox/content/)
#   3. installs the locked offline prefs (browser/app/profile/offox-prefs.js)
#   4. creates the Offox branding (browser/branding/offox)
#   5. makes FireLine the only built-in search engine
#   6. writes a mozconfig for the platform
#
# Tested against the esr153 branch (see fork/FIREFOX_VERSION).

import argparse
import json
import os
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
SRC = os.path.join(REPO, "browser", "components", "offox")
PREFS = os.path.join(REPO, "browser", "app", "profile", "offox-prefs.js")
GENERATED = {"jar.mn", "moz.build"}


def log(msg):
    print(f"[offox] {msg}")


def apply_patches(ff):
    patches = sorted(f for f in os.listdir(os.path.join(HERE, "patches")) if f.endswith(".patch"))
    use_git = os.path.isdir(os.path.join(ff, ".git"))
    for name in patches:
        path = os.path.join(HERE, "patches", name)
        if use_git:
            cmd = lambda *extra: ["git", "-C", ff, "apply", *extra, path]
        else:
            cmd = lambda *extra: ["patch", "-d", ff, "-p1", "-f", "-s", *extra, "-i", path]
        dry = "--check" if use_git else "--dry-run"
        if subprocess.run(cmd("-R", dry), capture_output=True).returncode == 0:
            log(f"{name}: already applied")
            continue
        r = subprocess.run(cmd(dry), capture_output=True, text=True)
        if r.returncode != 0:
            sys.exit(f"[offox] {name} does not apply to this Firefox tree:\n{r.stdout}{r.stderr}")
        subprocess.run(cmd(), check=True)
        log(f"{name}: applied")


def install_component(ff):
    dest = os.path.join(ff, "browser", "components", "offox")
    if os.path.abspath(dest) != os.path.abspath(SRC):
        if os.path.isdir(dest):
            shutil.rmtree(dest)
        shutil.copytree(SRC, dest)
    files = []
    for base, dirs, names in os.walk(dest):
        dirs[:] = [d for d in dirs if d not in ("node_modules", "__pycache__")]
        for n in names:
            rel = os.path.relpath(os.path.join(base, n), dest).replace(os.sep, "/")
            if rel not in GENERATED:
                files.append(rel)
    files.sort()
    lines = [
        "# This Source Code Form is subject to the terms of the Mozilla Public",
        "# License, v. 2.0. If a copy of the MPL was not distributed with this",
        "# file, You can obtain one at http://mozilla.org/MPL/2.0/.",
        "",
        "# Generated by Offox fork/apply.py - do not edit.",
        "",
        "browser.jar:",
        "% resource offox %res/offox/",
        "% content offox %content/offox/",
    ]
    for rel in files:
        if rel.startswith("content/"):
            lines.append(f"  content/offox/{rel[len('content/'):]} ({rel})")
        else:
            lines.append(f"  res/offox/{rel} ({rel})")
    with open(os.path.join(dest, "jar.mn"), "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    with open(os.path.join(dest, "moz.build"), "w", newline="\n") as f:
        f.write(
            "# This Source Code Form is subject to the terms of the Mozilla Public\n"
            "# License, v. 2.0. If a copy of the MPL was not distributed with this\n"
            "# file, You can obtain one at http://mozilla.org/MPL/2.0/.\n\n"
            'with Files("**"):\n'
            '    BUG_COMPONENT = ("Firefox", "General")\n\n'
            'JAR_MANIFESTS += ["jar.mn"]\n'
        )
    log(f"browser/components/offox: {len(files)} files")


def install_prefs(ff):
    dest = os.path.join(ff, "browser", "app", "profile", "offox-prefs.js")
    if os.path.abspath(dest) != os.path.abspath(PREFS):
        shutil.copy(PREFS, dest)
    log("offline prefs installed")


