def install_branding(ff):
    branding = os.path.join(ff, "browser", "branding")
    dest = os.path.join(branding, "offox")
    if os.path.isdir(dest):
        shutil.rmtree(dest)
    shutil.copytree(os.path.join(branding, "unofficial"), dest)
    # Generated images (tools/make-branding.py).
    overlay = os.path.join(HERE, "branding-images", "offox")
    for base, _dirs, names in os.walk(overlay):
        for n in names:
            src = os.path.join(base, n)
            rel = os.path.relpath(src, overlay)
            os.makedirs(os.path.dirname(os.path.join(dest, rel)), exist_ok=True)
            shutil.copy(src, os.path.join(dest, rel))
    write = lambda rel, text: open(os.path.join(dest, rel), "w", newline="\n").write(text)
    write(os.path.join("locales", "en-US", "brand.ftl"), BRAND_FTL)
    write(os.path.join("locales", "en-US", "brand.properties"), BRAND_PROPERTIES)
    write(os.path.join("pref", "firefox-branding.js"), BRANDING_PREFS)
    write(
        "configure.sh",
        "# This Source Code Form is subject to the terms of the Mozilla Public\n"
        "# License, v. 2.0. If a copy of the MPL was not distributed with this\n"
        "# file, You can obtain one at http://mozilla.org/MPL/2.0/.\n\n"
        "MOZ_APP_DISPLAYNAME=Offox\n"
        "MOZ_MACBUNDLE_ID=offox\n",
    )
    nsi = os.path.join(dest, "branding.nsi")
    text = open(nsi).read()
    replacements = {
        '"Mozilla Developer Preview"': '"Offox"',
        '"mozilla.org"': '"Offox"',
        '"https://www.mozilla.org"': '"https://fireline.offox/"',
        '"https://support.mozilla.org"': '"https://fireline.offox/"',
        '!define Channel "unofficial"': '!define Channel "offox"',
    }
    for old, new in replacements.items():
        text = text.replace(old, new)
    open(nsi, "w", newline="\n").write(text)
    log("branding: browser/branding/offox")


