def install_search(ff):
    dumps = os.path.join(ff, "services", "settings", "dumps", "main")
    config = os.path.join(dumps, "search-config-v2.json")
    data = json.load(open(config, encoding="utf-8"))
    records = [r for r in data["data"] if r.get("recordType") == "availableLocales"]
    records.append(FIRELINE_ENGINE)
    records.append({
        "globalDefault": "fireline",
        "id": "6f6b6f66-6669-4c69-a865-000000000002",
        "last_modified": 1790000000000,
        "recordType": "defaultEngines",
        "schema": 1790000000000,
        "specificDefaults": [],
    })
    records.append({
        "id": "6f6b6f66-6669-4c69-a865-000000000003",
        "last_modified": 1790000000000,
        "orders": [],
        "recordType": "engineOrders",
        "schema": 1790000000000,
    })
    data["data"] = records
    json.dump(data, open(config, "w", encoding="utf-8", newline="\n"), indent=2)
    icons = os.path.join(dumps, "search-config-icons.json")
    if os.path.exists(icons):
        d = json.load(open(icons, encoding="utf-8"))
        d["data"] = []
        json.dump(d, open(icons, "w", encoding="utf-8", newline="\n"), indent=2)
    # The address bar's default top sites (Wikipedia, YouTube, Reddit...)
    # come from this dump; Offox shows your own websites instead.
    top_sites = os.path.join(dumps, "top-sites.json")
    if os.path.exists(top_sites):
        d = json.load(open(top_sites, encoding="utf-8"))
        d["data"] = []
        json.dump(d, open(top_sites, "w", encoding="utf-8", newline="\n"), indent=2)
    log("search: FireLine is the only engine")


def install_mozconfig(ff, platform):
    src = os.path.join(HERE, f"mozconfig.{platform}")
    shutil.copy(src, os.path.join(ff, "mozconfig"))
    log(f"mozconfig: {os.path.basename(src)}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("firefox", help="Firefox ESR source folder")
    parser.add_argument("--mozconfig", choices=["linux", "windows"],
                        help="also copy offox/fork/mozconfig.<platform> to <tree>/mozconfig")
    args = parser.parse_args()
    ff = os.path.abspath(args.firefox)
    if not os.path.exists(os.path.join(ff, "mach")):
        sys.exit(f"[offox] {ff} is not a Firefox source folder (no mach)")
    apply_patches(ff)
    install_component(ff)
    install_prefs(ff)
    install_branding(ff)
    install_search(ff)
    if args.mozconfig:
        install_mozconfig(ff, args.mozconfig)
    log("done. Build with: MOZCONFIG=offox/fork/mozconfig.linux ./mach build && ./mach package")


if __name__ == "__main__":
    main()
